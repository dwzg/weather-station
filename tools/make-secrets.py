#!/usr/bin/env python3
"""Writes the git-ignored secrets of both firmwares from the homelab secrets folder:
include/secrets.h (ESP8266) and rust/firmware/secrets.env (ESP32-S2).

    ~/.config/homelab/weather-station/wifi.env    WIFI_SSID=, WIFI_PASS=
    ~/.config/homelab/weather-station/ota.pass    the OTA password (PlatformIO sends it)
    ~/.config/homelab/stack-env/weatherpage.env   INGEST_API_KEY= (POST-only key of the weather app)

Only a hash of the OTA password goes into the firmware: its MD5 for ArduinoOTA,
its SHA-256 as the HMAC key of the S2's updates (tools/ota-s2.py).
"""
import hashlib
import json
import os
import pathlib

home = pathlib.Path.home() / ".config" / "homelab"
root = pathlib.Path(__file__).resolve().parent.parent


def env(path):
    out = {}
    for line in path.read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


wifi = env(home / "weather-station" / "wifi.env")
# Longer values do not fit the Wi-Fi drivers' fields and would be cut or emptied.
if len(wifi["WIFI_SSID"].encode()) > 32:
    raise SystemExit("WIFI_SSID is longer than 32 bytes")
if not (8 <= len(wifi["WIFI_PASS"].encode()) <= 64 or wifi["WIFI_PASS"] == ""):
    raise SystemExit("WIFI_PASS must be 8 to 64 bytes (or empty for an open network)")
app = env(home / "stack-env" / "weatherpage.env")
ota = (home / "weather-station" / "ota.pass").read_text().strip()


def c(s):  # a C string literal; json escaping is a subset C accepts for ASCII
    s.encode("ascii")
    return json.dumps(s)


lines = [
    "#pragma once",
    "// Generated by tools/make-secrets.py. Never commit this file.",
    f"#define WIFI_SSID {c(wifi['WIFI_SSID'])}",
    f"#define WIFI_PASS {c(wifi['WIFI_PASS'])}",
    '#define API_URL "https://weather.wtzg.de/api/weather"',
    f"#define API_KEY {c(app['INGEST_API_KEY'])}",
    f"#define OTA_PASSWORD_MD5 {c(hashlib.md5(ota.encode()).hexdigest())}",
]


def write_private(path, text):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    path.chmod(0o600)
    print(f"wrote {path}")


write_private(root / "include" / "secrets.h", "\n".join(lines) + "\n")

env_values = {
    "WIFI_SSID": wifi["WIFI_SSID"],
    "WIFI_PASS": wifi["WIFI_PASS"],
    "API_URL": "https://weather.wtzg.de/api/weather",
    "API_KEY": app["INGEST_API_KEY"],
    "OTA_KEY": hashlib.sha256(ota.encode()).hexdigest(),
}
for k, v in env_values.items():
    # build.rs reads KEY=value lines and trims the value.
    if "\n" in v or v != v.strip():
        raise SystemExit(f"{k}: newlines or surrounding spaces cannot go into secrets.env")
env_lines = ["# Generated by tools/make-secrets.py. Never commit this file."]
env_lines += [f"{k}={v}" for k, v in env_values.items()]
write_private(root / "rust" / "firmware" / "secrets.env", "\n".join(env_lines) + "\n")
