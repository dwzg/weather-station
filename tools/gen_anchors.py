#!/usr/bin/env python3
"""Writes src/trust_anchors.h from the root certificates in certs/.

The station trusts only Let's Encrypt's roots (X1, X2 and the 2025 generation
YR, YE), not the leaf or intermediates, so certificate renewals and new
intermediates need no firmware update. Re-run after changing certs/.
"""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
pems = sorted((root / "certs").glob("*.pem"))
out = ["#pragma once", "// Generated by tools/gen_anchors.py from certs/*.pem. Do not edit.", "#include <pgmspace.h>", "",
       "static const char kTrustAnchors[] PROGMEM = R\"PEM("]
for p in pems:
    out.append(p.read_text().strip())
out.append(")PEM\";")
(root / "src" / "trust_anchors.h").write_text("\n".join(out) + "\n")
print(f"{len(pems)} anchors: " + ", ".join(p.stem for p in pems))
